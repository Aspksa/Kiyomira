import type { ПровайдерМодели, КонтекстМодели } from './01-ПровайдерМодели.ts';

// Только для локальной проверки. Не выполняет настоящую генерацию ИИ.
export class ТестоваяМодель implements ПровайдерМодели {
  async создатьОтвет(история: readonly КонтекстМодели[]): Promise<string> {
    const последнее = история.at(-1);
    return `Тестовый ответ Kiyomira: ${последнее?.текст ?? ''}`;
  }
}
