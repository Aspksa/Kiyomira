// Lightweight, source-scoped classification. Labels describe the *kind of
// statement*, not factual truth. No model requests or independent conclusions.
export type ВидПамяти='эпизодическая'|'семантическая'|'процедурная'|
  'решения'|'ошибки'|'предпочтения'|'проектная'|'временная';
export function классифицироватьПамять(текст:string):{вид:ВидПамяти;основание:string}[]{
  const defs:{вид:ВидПамяти;pattern:RegExp;основание:string}[]=[
    {вид:'эпизодическая',pattern:/(?:встреча|событие|случилось|произошло|ездил|поездка)/iu,основание:'упомянуто событие'},
    {вид:'семантическая',pattern:/(?:[^\n:]{3,60}[:：]\s*[^\n]{2,130}|означает|определение|является)/iu,основание:'формулировка факта или понятия'},
    {вид:'процедурная',pattern:/(?:инструкция|шаги|порядок действий|сначала.+затем|как сделать)/iu,основание:'последовательность действий'},
    {вид:'решения',pattern:/(?:решил|выбрал|утвердил|одобрил|решение)/iu,основание:'формулировка решения'},
    {вид:'ошибки',pattern:/(?:ошибка|сбой|исправил|не работает|исправление)/iu,основание:'упомянута проблема'},
    {вид:'предпочтения',pattern:/(?:предпочитаю|нравится|люблю|хочу|не хочу)/iu,основание:'выражено предпочтение'},
    {вид:'проектная',pattern:/(?:проект|github|репозитор|коммит|pull request|pr #)/iu,основание:'упомянут проект'},
    {вид:'временная',pattern:/(?:20\d{2}-\d{2}-\d{2}|вчера|сегодня|завтра|планирую|раньше)/iu,основание:'временное указание'}
  ];
  return defs.filter(x=>x.pattern.test(текст.slice(0,4000)))
    .map(x=>({вид:x.вид,основание:x.основание}));
}
