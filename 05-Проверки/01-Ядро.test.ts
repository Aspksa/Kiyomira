import { test } from 'node:test';
import { strict as assert } from 'node:assert';
import { Ядро } from '../01-Ядро/02-Управление.ts';
import { ТестоваяМодель } from '../04-Модели/02-ТестоваяМодель.ts';
import { ПамятьДиалога } from '../02-Память/01-ПамятьДиалога.ts';
import { ОчередьЗадач } from '../03-Задачи/01-ОчередьЗадач.ts';

test('жизненный цикл и диалог', async () => {
  const ядро = new Ядро(new ТестоваяМодель());
  await assert.rejects(() => ядро.ответить('до запуска'), /Ядро не запущено/);
  ядро.запустить();
  assert.match(await ядро.ответить('привет'), /привет/);
  assert.equal(ядро.диагностика().сообщений, 2);
  await ядро.остановить();
  await assert.rejects(() => ядро.ответить('после остановки'), /Ядро не запущено/);
});

test('лимит памяти и защита копии', () => {
  const память = new ПамятьДиалога(2);
  память.добавить('пользователь', '1');
  память.добавить('ассистент', '2');
  память.добавить('пользователь', '3');
  const записи = память.получить();
  assert.deepEqual(записи.map(х => х.текст), ['2', '3']);
  записи.pop();
  assert.equal(память.размер(), 3);
  память.закрыть();
});

test('очередь сохраняет порядок после ошибки', async () => {
  const очередь = new ОчередьЗадач();
  const история: number[] = [];
  const первая = очередь.добавить(() => { история.push(1); throw new Error('сбой'); });
  const вторая = очередь.добавить(() => { история.push(2); });
  await assert.rejects(первая);
  await вторая;
  await очередь.дождаться();
  assert.deepEqual(история, [1, 2]);
  assert.equal(очередь.размер(), 0);
  assert.equal(очередь.последниеОшибки().length, 1);
});
